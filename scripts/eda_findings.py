    "- Partial-correlation lags above the band: "
    + "; ".join(f"{c} {v or 'none'}" for c, v in lag["lags_above_null_band_partial"].items())
    + ". No clear decay pattern: the data do not settle max lag.",
    "",
    fig(lag["figure"]),
    "",
    "## Collinearity",

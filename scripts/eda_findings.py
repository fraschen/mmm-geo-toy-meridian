    f"+/- {pop['revenue']['loglog_slope_se']:.2f}); so does spend (Spearman "
    f"{pop['spend']['spearman']:.3f}, slope {pop['spend']['loglog_slope']:.2f} +/- "
    f"{pop['spend']['loglog_slope_se']:.2f}). Revenue per capita CV across geos "
    f"{pct(pop['revenue_per_capita_cv_across_geos'])}; spend per capita CV "
    f"{pct(pop['spend_per_capita_cv_across_geos'])}.",
    "- Geo means of the controls barely track population (Spearman "
    + ", ".join(f"{k} {v:+.2f}" for k, v in pop["control_geo_mean_spearman_with_population"].items())
    + ").",
    "",
    fig(pop["figure"]),
    "",
    "## Spend relative to each geo's maximum",
    "- Zero-spend geo-weeks: " + ", ".join(f"{c} {pct(gm[c]['share_zero_geo_weeks'])}" for c in CHANNELS)
    + ". Median non-zero week sits at "
    + ", ".join(f"{c} {gm[c]['nonzero_ratio_to_geo_max_quantiles']['0.5']:.2f}" for c in CHANNELS)
    + " of the geo max.",
    "- Last 52 weeks scaled by 1.2 would exceed the geo's historical max in "
    + ", ".join(f"{c} {pct(gm[c]['last52_share_geo_weeks_beyond_geo_max_if_x1.2'])}" for c in CHANNELS)
    + " of geo-weeks; scaled by 1.5: "
    + ", ".join(f"{c} {pct(gm[c]['last52_share_geo_weeks_beyond_geo_max_if_x1.5'])}" for c in CHANNELS)
    + ".",
    "",
    fig(gm["figure"]),
    "",
    "## Controls: confounders?",
    "- Within-geo correlation with revenue: "
    + ", ".join(f"{k} {v['revenue']:+.2f}" for k, v in cc["within_geo_corr"].items())
    + f". Controls also correlate with spend (max |r| "
    f"{cc['max_abs_corr_control_with_spend_within_geo']:.2f}): competitor_sales_control with "
    + ", ".join(f"{c} {cc['within_geo_corr']['competitor_sales_control'][c]:+.2f}" for c in CHANNELS)
    + ". Both controls move with spend and with revenue, so they are confounders and must "

    f"p = {t['p_value']:.3f}; with 13 lags p = {tr['hac_maxlags_13']['p_value']:.3f}). "
    f"Last 52 weeks vs first 52: {tr['first_52_vs_last_52_revenue_pct']:+.1f}%.",
    "",
    fig(tr["figure"]),
    "",
    "## Yearly seasonality vs chance",
    f"- Week-of-year means explain R2 = {se['observed_r2']:.3f} of detrended national "
    f"revenue. Pure noise of the same length gives {se['null_iid_mean']:.3f} on average "
    f"(95th percentile {se['null_iid_p95']:.3f}); p = {se['p_value_iid']:.2f} (iid null), "
    f"{se['p_value_ar1']:.2f} (AR(1) null, phi = {se['detrended_lag1_autocorr']:.3f}). "
    f"Per geo, {se['geos_significant_5pct_iid']} of {d['n_geos']} geos are significant at "
    f"5% ({se['geos_expected_by_chance']:.0f} expected by chance). "
    f"Seasonality detected: {se['seasonality_detected']}.",
    "",
    fig(se["figure"]),
    "",
    "## Noise floor",
    f"- Geo-week revenue: CV median {pct(nf['geo_weekly_cv']['median'])} "
    f"(range {pct(nf['geo_weekly_cv']['min'])}-{pct(nf['geo_weekly_cv']['max'])}); lag-1 "
    f"autocorrelation of detrended revenue median {nf['geo_lag1_autocorr']['median']:.3f}; "
    f"MAPE of a 13-week moving average {pct(nf['geo_mape_vs_13wk_ma']['median'])}.",
    f"- National weekly revenue: CV {pct(nf['national_weekly_cv'])}, lag-1 autocorrelation "
    f"{nf['national_lag1_autocorr']:.3f}, MAPE of a 13-week moving average "
    f"{pct(nf['national_mape_vs_13wk_ma'])}.",
    "- Weekly revenue is close to white noise around a slow trend, at both levels.",
    "",

    f"CV {pct(d['revenue_per_conversion']['cv'])}).",
    "- Spend share: " + ", ".join(f"{c} {pct(d['spend_share'][c])}" for c in CHANNELS) + ".",
    "",
    fig(d["figure_spend_share"]),
    "",
    "## Spend vs impressions (CPM)",
    "- Spend = impressions x a constant CPM in every channel: the largest deviation from "
    f"the channel median is {max(cpm[c]['max_abs_relative_deviation_from_median'] for c in CHANNELS) * 1e6:.2f} "
    "parts per million (float rounding). CPMs: "
    + ", ".join(f"{c} {cpm[c]['cpm_median']:.2f}" for c in CHANNELS) + ". "
    "Impressions therefore carry no information beyond spend, and Meridian's "
    "cost-per-media-unit outlier flags are rounding noise.",
    "",
    fig(cpm["figure"]),
    "",
    "## National trend",
    f"- Linear trend {t['slope_per_year_pct_of_mean']:.2f}% of mean revenue per year "
